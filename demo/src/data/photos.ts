import type { ImageMetadata } from "astro";

/**
 * Photos of the demo, all from the NASA Image and Video Library. Sources, credits and licenses
 * are listed in demo/PHOTOS.md.
 */
export interface Photo {
  /** NASA ID, also the file name */
  id: string;
  /** Local optimized image; null for the one served as a plain file from public/ */
  src: ImageMetadata | null;
  alt: string;
  caption: string;
  mission: string;
  /** Omitted when NASA only gives the archive date, not when the photo was taken */
  year?: string;
  credit: string;
}

const files = import.meta.glob<{ default: ImageMetadata }>(
  "../assets/nasa/*.jpg",
  { eager: true },
);

function image(id: string): ImageMetadata {
  const file = files[`../assets/nasa/${id}.jpg`];
  if (!file) throw new Error(`Missing photo: ${id}`);
  return file.default;
}

